const User = require('./User');
const Listing = require('./Listing');
const Admin = require('./Admin');
const AdminRole = require('./AdminRole');
const EscrowAccount = require('./EscrowAccount');
const TokenOrder = require('./TokenOrder');
const PpobOrder = require('./PpobOrder');
const PpobCatalog = require('./PpobCatalog');
const PpobSetting = require('./PpobSetting');
const Region = require('./Region');
const Category = require('./Category');
const Favorite = require('./Favorite');
const EscrowSale = require('./EscrowSale');
const SellerBalance = require('./SellerBalance');
const Withdrawal = require('./Withdrawal');

User.hasMany(Listing, { as: 'listings', foreignKey: 'userId', onDelete: 'CASCADE' });
Listing.belongsTo(User, { as: 'seller', foreignKey: 'userId' });
User.hasMany(Favorite, { as: 'favorites', foreignKey: 'userId', onDelete: 'CASCADE' });
Favorite.belongsTo(User, { as: 'user', foreignKey: 'userId' });
Listing.hasMany(Favorite, { as: 'favorites', foreignKey: 'listingId', onDelete: 'CASCADE' });
Favorite.belongsTo(Listing, { as: 'listing', foreignKey: 'listingId' });
User.hasMany(EscrowSale, { as: 'purchases', foreignKey: 'buyerId' });
EscrowSale.belongsTo(User, { as: 'buyer', foreignKey: 'buyerId' });
User.hasMany(EscrowSale, { as: 'sales', foreignKey: 'sellerId' });
EscrowSale.belongsTo(User, { as: 'seller', foreignKey: 'sellerId' });
EscrowSale.belongsTo(Listing, { as: 'listing', foreignKey: 'listingId' });
User.hasOne(SellerBalance, { as: 'sellerBalance', foreignKey: 'userId' });
SellerBalance.belongsTo(User, { as: 'user', foreignKey: 'userId' });
User.hasMany(Withdrawal, { as: 'withdrawals', foreignKey: 'userId' });
Withdrawal.belongsTo(User, { as: 'user', foreignKey: 'userId' });
User.hasMany(TokenOrder, { as: 'tokenOrders', foreignKey: 'userId', onDelete: 'CASCADE' });
TokenOrder.belongsTo(User, { as: 'user', foreignKey: 'userId' });
User.hasMany(PpobOrder, { as: 'ppobOrders', foreignKey: 'userId', onDelete: 'CASCADE' });
PpobOrder.belongsTo(User, { as: 'user', foreignKey: 'userId' });

Admin.belongsTo(AdminRole, { foreignKey: 'role', targetKey: 'key', as: 'adminRole', constraints: false });
AdminRole.hasMany(Admin, { foreignKey: 'role', sourceKey: 'key', as: 'admins', constraints: false });

module.exports = { User, Listing, Admin, AdminRole, EscrowAccount, TokenOrder, PpobOrder, PpobCatalog, PpobSetting, Region, Category, Favorite, EscrowSale, SellerBalance, Withdrawal };
